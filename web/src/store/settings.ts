import { create } from 'zustand'
import { persist } from 'zustand/middleware'

export interface SettingsStore {
  // Paths
  resumePath: string
  baseCvPath: string

  // Cascade
  cascadeEnabled: boolean
  stage1Model: string
  stage2Model: string
  stage3Model: string
  generationModel: string
  filterModel: string // used when cascade is disabled

  // Search
  searchSites: string[]
  maxJobs: number

  // Email
  emailRecipient: string
  autoSendEmail: boolean

  // Doc generation
  autoGenerateDocs: boolean

  // Hydration state (server defaults loaded?)
  _hydrated: boolean

  // Actions
  setResumePath: (v: string) => void
  setBaseCvPath: (v: string) => void
  setCascadeEnabled: (v: boolean) => void
  setStage1Model: (v: string) => void
  setStage2Model: (v: string) => void
  setStage3Model: (v: string) => void
  setGenerationModel: (v: string) => void
  setFilterModel: (v: string) => void
  setSearchSites: (v: string[]) => void
  toggleSite: (site: string) => void
  setMaxJobs: (v: number) => void
  setEmailRecipient: (v: string) => void
  setAutoSendEmail: (v: boolean) => void
  setAutoGenerateDocs: (v: boolean) => void
  hydrateFromServer: (config: ServerConfig) => void
}

export interface ServerConfig {
  available_models: string[]
  search_sites: string[]
  cascade_models: {
    stage1: string
    stage2: string
    stage3: string
  }
  generation_model: string
  default_resume_path: string
  default_base_cv_path: string
}

export const useSettingsStore = create<SettingsStore>()(
  persist(
    (set, get) => ({
      // Defaults (overwritten by server hydration)
      resumePath: 'resume.pdf',
      baseCvPath: 'base_cv.docx',
      cascadeEnabled: true,
      // Placeholders until /api/config answers — hydrateFromServer always
      // overwrites the model fields with the server's current config.
      stage1Model: 'claude-sonnet-5',
      stage2Model: 'claude-sonnet-5',
      stage3Model: 'claude-fable-5-2',
      generationModel: 'claude-opus-5-5',
      filterModel: 'claude-sonnet-5',
      searchSites: ['linkedin', 'indeed', 'glassdoor', 'zip_recruiter', 'ats_boards', 'industry_boards'],
      maxJobs: 0,
      emailRecipient: '',
      autoSendEmail: false,
      autoGenerateDocs: true,
      _hydrated: false,

      // Actions
      setResumePath: (v) => set({ resumePath: v }),
      setBaseCvPath: (v) => set({ baseCvPath: v }),
      setCascadeEnabled: (v) => set({ cascadeEnabled: v }),
      setStage1Model: (v) => set({ stage1Model: v }),
      setStage2Model: (v) => set({ stage2Model: v }),
      setStage3Model: (v) => set({ stage3Model: v }),
      setGenerationModel: (v) => set({ generationModel: v }),
      setFilterModel: (v) => set({ filterModel: v }),
      setSearchSites: (v) => set({ searchSites: v }),
      toggleSite: (site) => {
        const current = get().searchSites
        if (current.includes(site)) {
          set({ searchSites: current.filter((s) => s !== site) })
        } else {
          set({ searchSites: [...current, site] })
        }
      },
      setMaxJobs: (v) => set({ maxJobs: v }),
      setEmailRecipient: (v) => set({ emailRecipient: v }),
      setAutoSendEmail: (v) => set({ autoSendEmail: v }),
      setAutoGenerateDocs: (v) => set({ autoGenerateDocs: v }),

      hydrateFromServer: (config) => {
        // Models ALWAYS come from the server config: they are not persisted
        // (2026-09-01: a browser that had persisted stage3Model/generationModel
        // kept sending the pre-migration models on every UI-launched search).
        // A per-session override in the Settings panel still applies until reload.
        set({
          stage1Model: config.cascade_models.stage1,
          stage2Model: config.cascade_models.stage2,
          stage3Model: config.cascade_models.stage3,
          generationModel: config.generation_model,
          filterModel: config.cascade_models.stage2,
        })
        // Everything else hydrates once, then the user's persisted choices win
        if (!get()._hydrated) {
          set({
            searchSites: config.search_sites,
            resumePath: config.default_resume_path || get().resumePath,
            baseCvPath: config.default_base_cv_path || get().baseCvPath,
            _hydrated: true,
          })
        }
      },
    }),
    {
      name: 'candidate-settings',
      // Only persist user-set values, not transient state
      partialize: (state) => ({
        resumePath: state.resumePath,
        baseCvPath: state.baseCvPath,
        cascadeEnabled: state.cascadeEnabled,
        // model fields deliberately NOT persisted — see hydrateFromServer
        searchSites: state.searchSites,
        maxJobs: state.maxJobs,
        emailRecipient: state.emailRecipient,
        autoSendEmail: state.autoSendEmail,
        autoGenerateDocs: state.autoGenerateDocs,
        _hydrated: state._hydrated,
      }),
    }
  )
)
