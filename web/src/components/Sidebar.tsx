import Link from 'next/link'
import { usePathname } from 'next/navigation'
import { Button } from '@/components/ui/button'
import { useSearchStore } from '@/store/search'
import { useSettingsStore } from '@/store/settings'
import { SettingsPanel } from '@/components/SettingsPanel'
import { ThemeToggle } from './ThemeToggle'
import { api } from '@/lib/api'
import { cn } from '@/lib/utils'
import {
  BarChart3,
  Briefcase,
  Eye,
  Kanban,
  PenLine,
  ScrollText,
  HelpCircle,
  Play,
  Square,
  Pause,
  Loader2,
  Sparkles,
} from 'lucide-react'
import { useState } from 'react'

const NAV_ITEMS = [
  { href: '/jobs', label: 'Jobs', icon: Briefcase },
  { href: '/review', label: 'Review', icon: Eye },
  { href: '/kanban', label: 'Kanban', icon: Kanban },
  { href: '/stats', label: 'Stats', icon: BarChart3 },
  { href: '/input', label: 'Input', icon: PenLine },
  { href: '/logs', label: 'Logs', icon: ScrollText },
]

const BOTTOM_NAV_ITEMS = [
  { href: '/help', label: 'Help', icon: HelpCircle },
]

/**
 * Extract a short display name from a model ID.
 * e.g. "claude-haiku-4-5" → "Haiku", "claude-opus-4-8" → "Opus"
 */
function shortModelName(modelId: string): string {
  // Match known Claude model families
  const families: Record<string, string> = {
    'fable': 'Fable',
    'haiku': 'Haiku',
    'sonnet': 'Sonnet',
    'opus': 'Opus',
  }
  const lower = modelId.toLowerCase()
  for (const [key, label] of Object.entries(families)) {
    if (lower.includes(key)) return label
  }
  // For Gemini models like "gemini-2.0-flash"
  if (lower.includes('gemini')) {
    const parts = modelId.split('-')
    // Return e.g. "Gemini Flash"
    const flash = parts.find((p) => p.toLowerCase() === 'flash')
    const pro = parts.find((p) => p.toLowerCase() === 'pro')
    if (flash) return 'Gemini Flash'
    if (pro) return 'Gemini Pro'
    return 'Gemini'
  }
  // For ollama models like "ollama/llama3"
  if (lower.startsWith('ollama/')) {
    return modelId.split('/')[1] ?? modelId
  }
  // Fallback: return as-is but truncated
  return modelId.length > 12 ? modelId.slice(0, 12) + '...' : modelId
}

/**
 * Format search sites for display.
 * Shows first 2 names + remaining count, e.g. "LinkedIn, Indeed +4"
 */
function formatSites(sites: string[]): string {
  const displayNames: Record<string, string> = {
    linkedin: 'LinkedIn',
    indeed: 'Indeed',
    glassdoor: 'Glassdoor',
    zip_recruiter: 'ZipRecruiter',
    ats_boards: 'ATS',
    industry_boards: 'Industry',
  }
  if (sites.length === 0) return 'No sites'
  const named = sites.map((s) => displayNames[s] ?? s)
  if (named.length <= 2) return named.join(', ')
  return `${named[0]}, ${named[1]} +${named.length - 2}`
}

export function Sidebar() {
  const pathname = usePathname()
  const { active, paused, setStatus } = useSearchStore()
  const [actionLoading, setActionLoading] = useState(false)

  // Read settings from the Zustand store
  const settings = useSettingsStore()

  const handleStart = async () => {
    setActionLoading(true)
    try {
      const res = await api.search.start({
        cascade: settings.cascadeEnabled,
        limit: settings.maxJobs || 20,
        resume_path: settings.resumePath,
        base_cv_path: settings.baseCvPath,
        model_filter: settings.cascadeEnabled
          ? settings.stage2Model
          : settings.filterModel,
        model_generation: settings.generationModel,
        search_sites: settings.searchSites,
        stage1_model: settings.cascadeEnabled ? settings.stage1Model : undefined,
        stage2_model: settings.cascadeEnabled ? settings.stage2Model : undefined,
        stage3_model: settings.cascadeEnabled ? settings.stage3Model : undefined,
        send_email: settings.autoSendEmail,
        target_email: settings.emailRecipient || undefined,
        auto_generate_docs: settings.autoGenerateDocs,
      })
      setStatus({
        active: true,
        paused: false,
        progress: 0,
        statusText: 'Starting...',
        sessionId: res.session_id ?? null,
      })
    } catch {
      // Error handling is the caller's responsibility
    } finally {
      setActionLoading(false)
    }
  }

  const handleStop = async () => {
    setActionLoading(true)
    try {
      await api.search.stop()
      setStatus({
        active: false,
        paused: false,
        progress: 0,
        statusText: 'Idle',
      })
    } catch {
      // Error handling is the caller's responsibility
    } finally {
      setActionLoading(false)
    }
  }

  const handlePause = async () => {
    setActionLoading(true)
    try {
      await api.search.pause()
      setStatus({ paused: !paused })
    } catch {
      // Error handling is the caller's responsibility
    } finally {
      setActionLoading(false)
    }
  }

  return (
    <aside className="fixed inset-y-0 left-0 z-40 flex w-64 flex-col border-r border-border bg-card">
      {/* Logo / Title + Settings */}
      <div className="flex items-center gap-2 border-b border-border px-4 py-4">
        <Sparkles className="size-5 text-primary" />
        <span
          className="whitespace-nowrap text-[19px] tracking-wide text-foreground"
          style={{ fontFamily: 'var(--font-display), sans-serif' }}
        >
          AI Job Agent
        </span>
        <div className="ml-auto flex items-center gap-1">
          <ThemeToggle />
          <SettingsPanel />
        </div>
      </div>

      {/* Navigation */}
      <nav className="flex flex-1 flex-col gap-1 px-2 py-3">
        {NAV_ITEMS.map((item) => {
          const isActive =
            pathname === item.href ||
            (item.href !== '/' && pathname.startsWith(item.href))

          return (
            <Link key={item.href} href={item.href}>
              <div
                className={cn(
                  'flex items-center gap-2.5 rounded-lg px-3 py-2.5 text-base font-medium transition-colors duration-200 focus-visible:ring-2 focus-visible:ring-ring',
                  isActive
                    ? 'bg-primary/10 text-primary'
                    : 'text-muted-foreground hover:bg-muted hover:text-foreground'
                )}
              >
                <item.icon
                  className={cn(
                    'size-4 shrink-0',
                    isActive ? 'text-primary' : ''
                  )}
                />
                {item.label}
                {isActive && (
                  <div className="ml-auto size-1.5 rounded-full bg-primary" />
                )}
              </div>
            </Link>
          )
        })}

        {/* Spacer pushes Help to the bottom */}
        <div className="flex-1" />
        <div className="border-t border-border/60 pt-1">
          {BOTTOM_NAV_ITEMS.map((item) => {
            const isActive =
              pathname === item.href ||
              (item.href !== '/' && pathname.startsWith(item.href))

            return (
              <Link key={item.href} href={item.href}>
                <div
                  className={cn(
                    'flex items-center gap-2.5 rounded-lg px-3 py-2.5 text-base font-medium transition-colors duration-200 focus-visible:ring-2 focus-visible:ring-ring',
                    isActive
                      ? 'bg-primary/10 text-primary'
                      : 'text-muted-foreground hover:bg-muted hover:text-foreground'
                  )}
                >
                  <item.icon
                    className={cn(
                      'size-4 shrink-0',
                      isActive ? 'text-primary' : ''
                    )}
                  />
                  {item.label}
                  {isActive && (
                    <div className="ml-auto size-1.5 rounded-full bg-primary" />
                  )}
                </div>
              </Link>
            )
          })}
        </div>
      </nav>

      {/* Active settings summary */}
      <div className="border-t border-border px-3 py-2">
        <div className="flex flex-wrap gap-1">
          {settings.cascadeEnabled ? (
            <span className="inline-flex items-center rounded bg-primary/10 px-1.5 py-0.5 text-xs font-medium text-primary">
              S1: {shortModelName(settings.stage1Model)} &rarr; S2: {shortModelName(settings.stage2Model)} &rarr; S3: {shortModelName(settings.stage3Model)}
            </span>
          ) : (
            <span className="inline-flex items-center rounded bg-muted px-1.5 py-0.5 text-xs font-medium text-muted-foreground">
              Single: {shortModelName(settings.filterModel)}
            </span>
          )}
          <span className="inline-flex items-center rounded bg-muted px-1.5 py-0.5 text-xs font-medium text-muted-foreground">
            {formatSites(settings.searchSites)}
          </span>
          {settings.maxJobs > 0 && (
            <span className="inline-flex items-center rounded bg-muted px-1.5 py-0.5 text-xs font-medium text-muted-foreground">
              max {settings.maxJobs}
            </span>
          )}
        </div>
      </div>

      {/* Search controls */}
      <div className="border-t border-border p-3">
        <div className="mb-2 text-sm font-medium uppercase tracking-wider text-muted-foreground">
          Search
        </div>
        <div className="flex flex-col gap-1.5">
          {!active ? (
            <Button
              variant="default"
              size="sm"
              className="w-full gap-1.5 transition-colors duration-200 focus-visible:ring-2 focus-visible:ring-ring"
              onClick={handleStart}
              disabled={actionLoading || settings.searchSites.length === 0}
            >
              {actionLoading ? (
                <Loader2 className="size-3.5 animate-spin" />
              ) : (
                <Play className="size-3.5" />
              )}
              Start Search
            </Button>
          ) : (
            <>
              <Button
                variant="outline"
                size="sm"
                className="w-full gap-1.5 transition-colors duration-200 focus-visible:ring-2 focus-visible:ring-ring"
                onClick={handlePause}
                disabled={actionLoading}
              >
                {actionLoading ? (
                  <Loader2 className="size-3.5 animate-spin" />
                ) : (
                  <Pause className="size-3.5" />
                )}
                {paused ? 'Resume' : 'Pause'}
              </Button>
              <Button
                variant="destructive"
                size="sm"
                className="w-full gap-1.5 transition-colors duration-200 focus-visible:ring-2 focus-visible:ring-ring"
                onClick={handleStop}
                disabled={actionLoading}
              >
                {actionLoading ? (
                  <Loader2 className="size-3.5 animate-spin" />
                ) : (
                  <Square className="size-3.5" />
                )}
                Stop
              </Button>
            </>
          )}
        </div>
      </div>

    </aside>
  )
}
